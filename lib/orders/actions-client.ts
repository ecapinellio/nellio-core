/** Snake_case on purpose: this is the RPC's own JSON, passed through as is. */
export async function listDriverOrders(supabase: Client): Promise<QueryResult<DriverOrder[]>>
{
	const { data, error } = await supabase.rpc("list_driver_orders");
	if (error)
	{
		return { data: null, error };
	}
	return { data: data as unknown as DriverOrder[], error: null };
}

export interface DeliveryLineInput
{
	orderItemId: string;
	deliveredQuantity: number;
	reason?: string;
	note?: string;
}

export interface RecordDeliveryInput
{
	/** Generated by the phone so a retry after a timeout is a no-op. */
	deliveryId: string;
	/** Partial is derived by the server from the lines. */
	outcome: "delivered" | "failed";
	lines: DeliveryLineInput[];
	receiverName: string | null;
	signaturePath: string | null;
	photoPath: string | null;
	failureReason: string | null;
	failureNote: string | null;
	paymentMethod: string | null;
	amountCollected: number | null;
}

export async function recordDelivery(supabase: Client, orderId: string, input: RecordDeliveryInput): Promise<QueryResult<Json>>
{
	const { data, error } = await supabase.rpc("record_delivery", {
		p_delivery_id: input.deliveryId,
		p_order_id: orderId,
		p_outcome: input.outcome,
		p_lines: input.lines.map((l) => ({
			order_item_id: l.orderItemId,
			delivered_quantity: l.deliveredQuantity,
			...(l.reason !== undefined ? { reason: l.reason } : {}),
			...(l.note !== undefined ? { note: l.note } : {}),
		})) as unknown as Json,
		p_receiver_name: input.receiverName as string,
		p_signature_path: input.signaturePath as string,
		p_photo_path: input.photoPath as string,
		p_failure_reason: input.failureReason as string,
		p_failure_note: input.failureNote as string,
		p_payment_method: input.paymentMethod as string,
		p_amount_collected: input.amountCollected as number,
	});
	return { data, error };
}

/**
 * Uploads a proof to the private bucket and returns its path, to hand to
 * recordDelivery(). The path is built here, no upsert: a proof is immutable.
 */
export async function uploadDeliveryProof(
	supabase: Client,
	tenantId: string,
	deliveryId: string,
	kind: "signature" | "photo",
	file: Blob,
): Promise<QueryResult<string>>
{
	const path = `${tenantId}/${deliveryId}/${kind === "signature" ? "signature.png" : "photo.jpg"}`;
	const { error } = await supabase.storage.from("delivery-proofs").upload(path, file, {
		upsert: false,
		contentType: kind === "signature" ? "image/png" : "image/jpeg",
	});
	if (error)
	{
		// Storage errors aren't PostgrestErrors; shape them so callers handle one type.
		return { data: null, error: { name: "PostgrestError", message: error.message, details: "", hint: "", code: "storage" } as PostgrestError };
	}
	return { data: path, error: null };
}
