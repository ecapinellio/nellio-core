import type { PostgrestError, SupabaseClient } from "@supabase/supabase-js";
import type { Database, Json } from "@/lib/supabase/database.types";
import type { Order, QueryResult } from "@/lib/supabase/queries";

type Client = SupabaseClient<Database>;

// Thin wrappers over the transition RPCs. The server decides everything
// (role, tenant, allowed step, expected status); these only name the params.
// Generated Args types mark nullable text as `string`, hence the casts.

export interface AssignOrderInput
{
	driverId: string;
	deliveryDate: string;
	deliveryWindow: string | null;
	/** Status key the user saw: PT409 if the order moved since. */
	expectedStatus: string;
}

export async function assignOrder(supabase: Client, orderId: string, input: AssignOrderInput): Promise<QueryResult<Order>>
{
	const { data, error } = await supabase.rpc("assign_order", {
		p_order_id: orderId,
		p_driver_id: input.driverId,
		p_delivery_date: input.deliveryDate,
		p_delivery_window: input.deliveryWindow as string,
		p_expected_status: input.expectedStatus,
	});
	return { data, error };
}

